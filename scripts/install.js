// --- command transforms ------------------------------------------------------

function stripFrontmatter(text) {
  return text.replace(/^---\n[\s\S]*?\n---\n*/, '');
}

function transformCommand(text, kind) {
  if (kind === 'codex') {
    return stripFrontmatter(text).replace(/\$ARGUMENTS/g, 'the text typed after the command');
  }
  if (kind === 'opencode') {
    return text.replace(/^argument-hint:.*\n/m, '');
  }
  return text;
}

// --- rule text ---------------------------------------------------------------

function buildBlock(tier) {
  const rules = getCoreInstructions(tier);
  const label = tier === '100' ? '100% strict' : tier === '60' ? '60% lite' : '80% standard';
  return [
    BEGIN_MARK,
    '## say — ASD-STE100 controlled language (' + label + ')',
    '',
    rules,
    '',
    'Change tier: rerun the say installer with `--tier 60|80|100`. Remove: rerun with `--uninstall`.',
    END_MARK
  ].join('\n');
}

function buildRuleFile(tier, format) {
  const block = buildBlock(tier).replace(/^<!-- say:begin -->\n/, '').replace(/\n<!-- say:end -->$/, '');
  if (format === 'mdc') {
    return '---\ndescription: say ASD-STE100 controlled technical language\nglobs:\nalwaysApply: true\n---\n\n' + GENERATED + '\n\n' + block + '\n';
  }
  return GENERATED + '\n\n' + block + '\n';
}

// --- managed block in a shared instructions file ------------------------------

function escapeMark(mark) {
  return mark.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function upsertBlock(filePath, block, dry) {
  const existing = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : '';
  const re = new RegExp(escapeMark(BEGIN_MARK) + '[\\s\\S]*?' + escapeMark(END_MARK) + '\\n*');
  const cleaned = existing.replace(re, '').trimEnd();
  const next = cleaned ? cleaned + '\n\n' + block + '\n' : block + '\n';
  if (dry) {
    console.log('  [dry-run] write rule block -> ' + filePath);
    return;
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, next, 'utf8');
  console.log('  rule block -> ' + filePath);
}

function removeBlock(filePath, dry) {
  if (!fs.existsSync(filePath)) return;
  const existing = fs.readFileSync(filePath, 'utf8');
  const re = new RegExp(escapeMark(BEGIN_MARK) + '[\\s\\S]*?' + escapeMark(END_MARK) + '\\n*');
  if (!re.test(existing)) return;
  const next = existing.replace(re, '').trimEnd();
  if (dry) {
    console.log('  [dry-run] remove rule block <- ' + filePath);
    return;
  }
  if (next) {
    fs.writeFileSync(filePath, next + '\n', 'utf8');
  } else {
    fs.unlinkSync(filePath);
  }
  console.log('  rule block removed <- ' + filePath);
}

// --- file copying ------------------------------------------------------------

function log(action, from, to) {
  const rel = path.relative(PLUGIN_ROOT, from) || path.basename(from);
  console.log('  ' + action + ' ' + rel + ' -> ' + to);
}

function copyFile(src, dest, dry) {
  if (dry) {
    console.log('  [dry-run] copy -> ' + dest);
    return;
  }
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(src, dest);
  log('copy', src, dest);
}

function copyDir(src, dest, dry) {
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const from = path.join(src, entry.name);
    const to = path.join(dest, entry.name);
    if (entry.isDirectory()) copyDir(from, to, dry);
    else copyFile(from, to, dry);
  }
}

function writeManagedFile(filePath, content, dry) {
  if (dry) {
    console.log('  [dry-run] write ' + filePath);
    return;
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, 'utf8');
  console.log('  write ' + filePath);
}

function removeTree(target, dry) {
  if (!fs.existsSync(target)) return;
  if (dry) {
    console.log('  [dry-run] remove ' + target);
    return;
  }
  fs.rmSync(target, { recursive: true, force: true });
  console.log('  remove ' + target);
}

function installSkills(dir, uninstall, dry) {
  if (!dir) return;
  for (const skill of SKILL_DIRS) {
    const dest = path.join(dir, skill);
    if (uninstall) {
      removeTree(dest, dry);
    } else {
      copyDir(path.join(PLUGIN_ROOT, 'skills', skill), dest, dry);
    }
  }
  if (!uninstall) {
    copyFile(path.join(PLUGIN_ROOT, 'scripts', 'say-linter.js'), path.join(dir, 'say-check', 'say-linter.js'), dry);
  }
}

function installCommands(spec, baseDir, uninstall, dry) {
  if (!spec || !baseDir) return;
  if (uninstall) {
    for (const file of spec.files) removeTree(path.join(baseDir, file), dry);
    return;
  }
  for (const file of spec.files) {
    const src = path.join(PLUGIN_ROOT, 'commands', file);
    const raw = fs.readFileSync(src, 'utf8');
    const dest = path.join(baseDir, file);
    if (dry) {
      console.log('  [dry-run] command ' + file + ' (' + spec.transform + ') -> ' + dest);
    } else {
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      fs.writeFileSync(dest, transformCommand(raw, spec.transform), 'utf8');
      console.log('  command ' + file + ' -> ' + dest);
    }
  }
}

// --- per-agent install -------------------------------------------------------

function resolveTarget(holder, scope, opts) {
  if (!holder || !holder[scope]) return null;
  return scope === 'global' ? holder.global(opts.home) : holder.project(opts.cwd);
}

function installAgent(name, opts) {
  const spec = AGENTS[name];
  const tier = normalizeMode(opts.tier) || '80';
  const scope = opts.project ? 'project' : 'global';
  console.log('\n== ' + spec.label + ' (' + (opts.uninstall ? 'uninstall' : 'install tier ' + tier + ', ' + scope) + ') ==');

  installSkills(resolveTarget(spec.skills, scope, opts), opts.uninstall, opts.dry);
  installCommands(spec.commands, resolveTarget(spec.commands, scope, opts), opts.uninstall, opts.dry);

  if (spec.block) {
    const target = spec.block[scope] ? (scope === 'global' ? spec.block.global(opts.home) : path.join(opts.cwd, spec.block.project)) : null;    if (target) {
      if (opts.uninstall) removeBlock(target, opts.dry);
      else upsertBlock(target, buildBlock(tier), opts.dry);
    } else if (!opts.uninstall) {
      console.log('  (no ' + scope + ' rule file for this agent)');
    }
  }

  if (spec.rule) {
    const target = scope === 'global' ? spec.rule.global && spec.rule.global(opts.home) : path.join(opts.cwd, spec.rule.project);
    if (target) {
      if (opts.uninstall) {
        removeTree(target, opts.dry);
      } else {
        writeManagedFile(target, buildRuleFile(tier, spec.rule.format), opts.dry);
      }
    } else if (!opts.uninstall) {
      console.log('  (no ' + scope + ' rule file for this agent)');
    }
  }

  if (!opts.uninstall && spec.note) console.log('  note: ' + spec.note);
}

