// Remove empty parent directories up to (not including) stopDir.
function pruneEmptyDirs(startDir, stopDir) {
  let dir = path.resolve(startDir);
  const stop = path.resolve(stopDir);
  while (dir.startsWith(stop) && dir !== stop) {
    try {
      fs.rmdirSync(dir);
    } catch (e) {
      return; // not empty or missing: stop pruning
    }
    dir = path.dirname(dir);
  }
}

function runEmbed(opts) {
  const outDir = opts.out || PLUGIN_ROOT;
  const tier = normalizeMode(opts.tier) || '80';
  console.log('\n== embed harness bundles (' + (opts.uninstall ? 'uninstall' : 'tier ' + tier) + ') -> ' + outDir + ' ==');

  for (const entry of EMBED_FILES) {
    const target = path.join(outDir, entry.file);
    if (opts.uninstall) {
      removeTree(target, opts.dry);
      pruneEmptyDirs(path.dirname(target), outDir);
      continue;
    }
    if (entry.kind === 'block') {
      upsertBlock(target, buildBlock(tier), opts.dry);
    } else if (entry.kind === 'import') {
      writeManagedFile(target, GENERATED + '\n\n@AGENTS.md\n', opts.dry);
    } else if (entry.kind === 'rule') {
      writeManagedFile(target, buildRuleFile(tier, entry.format), opts.dry);
    } else if (entry.kind === 'skills') {
      for (const skill of SKILL_DIRS) {
        copyDir(path.join(PLUGIN_ROOT, 'skills', skill), path.join(target, skill), opts.dry);
      }
      copyFile(path.join(PLUGIN_ROOT, 'scripts', 'say-linter.js'), path.join(target, 'say-check', 'say-linter.js'), opts.dry);
    } else if (entry.kind === 'commands') {
      installCommands({ files: entry.files, transform: entry.transform }, target, false, opts.dry);
    }
  }
  console.log('\nDone. Commit the generated directories to ship them with the repo.');
}

// --- CLI ---------------------------------------------------------------------

function usage() {
  return [
    'say multi-harness installer',
    '',
    'Usage:',
    '  node scripts/install.js <agent> [--tier 60|80|100] [--project] [--uninstall] [--dry-run] [--home <dir>]',
    '  node scripts/install.js all',
    '  node scripts/install.js embed [--out <dir>] [--tier 60|80|100] [--uninstall] [--dry-run]',
    '  node scripts/install.js --list',
    '',
    'Agents: ' + Object.keys(AGENTS).join(' | '),
    '',
    'AGENTS.md-standard harnesses (Zed, Jules, Warp, VS Code, Junie, Devin, Aider):',
    'use any agent name with --project; the AGENTS.md block works for all of them.'
  ].join('\n');
}

function main() {
  const argv = process.argv.slice(2);
  const opts = { tier: '80', project: false, uninstall: false, dry: false, home: require('os').homedir(), cwd: process.cwd(), out: null };

  const positional = [];
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--tier') opts.tier = argv[++i];
    else if (a === '--project') opts.project = true;
    else if (a === '--uninstall') opts.uninstall = true;
    else if (a === '--dry-run') opts.dry = true;
    else if (a === '--home') opts.home = path.resolve(argv[++i]);
    else if (a === '--out') opts.out = path.resolve(argv[++i]);
    else if (a === '--list') {
      for (const [name, spec] of Object.entries(AGENTS)) console.log(name.padEnd(10) + spec.label);
      return;
    } else if (a === '--help' || a === '-h') {
      console.log(usage());
      return;
    } else positional.push(a);
  }

  const target = positional[0];
  if (!target || (!AGENTS[target] && target !== 'all' && target !== 'embed')) {
    console.error(usage());
    process.exit(1);
  }
  if (opts.tier !== '80' && !normalizeMode(opts.tier)) {
    console.error('Invalid --tier: ' + opts.tier + ' (use 60, 80, or 100)');
    process.exit(1);
  }

  if (target === 'embed') {
    runEmbed(opts);
    return;
  }

  for (const name of target === 'all' ? Object.keys(AGENTS) : [target]) installAgent(name, opts);
  console.log('\nDone.');
}

main();
